import { test, expect } from '@playwright/test'

test('receipt prints on white paper without the dark app background', async ({ page }, testInfo) => {
  const errors: string[] = []
  const failures: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (['error', 'warning'].includes(message.type())) errors.push(message.text()) })
  page.on('requestfailed', request => failures.push(request.url()))
  page.on('response', response => { if (response.status() >= 400) failures.push(response.url()) })
  await page.route('https://fonts.googleapis.com/**', route => route.fulfill({ contentType: 'text/css', body: '' }))
  await page.goto('/')
  await page.locator('.product-card').filter({ hasText: 'Golden Lions Shirt' }).click()
  await page.locator('.product-card').filter({ hasText: 'Bulldogs Shirt' }).click()
  await page.locator('.charge-button').click()
  const receipt = page.getByRole('dialog', { name: 'Receipt #1029' })
  await expect(receipt).toBeVisible()
  await expect(page.locator('.toast')).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('receipt-desktop.png') })
  for (const width of [390, 360]) {
    await page.setViewportSize({ width, height: 844 })
    await expect(receipt).toBeInViewport()
    expect(await receipt.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await receipt.getByRole('button', { name: 'Print receipt' }).scrollIntoViewIfNeeded()
    await page.screenshot({ path: testInfo.outputPath(`receipt-mobile-${width}.png`) })
  }
  await page.emulateMedia({ media: 'print' })
  await page.screenshot({ path: testInfo.outputPath('receipt-print.png'), fullPage: true })
  await page.pdf({ path: testInfo.outputPath('receipt.pdf'), format: 'A4', printBackground: true, displayHeaderFooter: false })
  expect(await page.locator('html').evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(255, 255, 255)')
  await expect(receipt.locator('.receipt-lines > div')).toHaveCount(2)
  await expect(receipt.locator('.receipt-total')).toContainText('₱1378.00')
  expect(errors).toEqual([])
  expect(failures).toEqual([])
})

test('current sale printer previews an unpaid copy without charging or changing stock', async ({ page }) => {
  await page.route('https://fonts.googleapis.com/**', route => route.fulfill({ contentType: 'text/css', body: '' }))
  await page.goto('/')
  await page.locator('.checkout-actions').getByTitle('Print receipt', { exact: true }).click()
  await expect(page.locator('.toast')).toContainText('Add an item before printing')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.locator('.product-card').first().click()
  const before = await page.evaluate(() => ({ ...localStorage }))
  await page.locator('.checkout-actions').getByTitle('Print receipt', { exact: true }).click()
  const receipt = page.getByRole('dialog', { name: 'Receipt Current sale' })
  await expect(receipt).toContainText('UNPAID · CURRENT SALE')
  await expect(receipt).toContainText('Total due')
  await expect(receipt).not.toContainText('Payment received')
  await page.evaluate(() => { window.print = () => { document.documentElement.dataset.printCalled = 'true' } })
  await receipt.getByRole('button', { name: 'Print receipt', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-print-called', 'true')
  await receipt.getByRole('button', { name: 'Close', exact: true }).click()
  expect(await page.evaluate(() => ({ ...localStorage }))).toEqual(before)
  await page.locator('.charge-button').click()
  await expect(page.getByRole('dialog', { name: 'Receipt #1029' })).toContainText('Payment received')
})
